// tl-test-new DPI Guest Mode testbench for the XSAICache matrix TestTop.
//
// Drives the same TileLink cycle as the Verilator host-mode main loop
// (main/V3/v3_main.cpp), but through the DPI-C interface exported by
// libtltest_dpi.so (see main/DPI/tilelink_dpi.cpp for the protocol):
//
//   TileLinkSystemInitialize()
//   [ per cycle, at negedge: Tick -> Push A,B,C,E,D -> Tock -> Pull A,B,C,E,D ]
//   TileLinkSystemFinalize() when TileLinkSystemIsAlive() returns 0
//
// Device ids follow the static PortGen order (main/PortGen/portgen_static.cpp),
// matching configs/coupledL2-test-matrix-trace.tltest.ini (core=1 tl_c=1
// tl_ul=0 tl_m=1), i.e. the TestTop generated by
//   make -C dut/XSCache test-top-matrix NUM_CORE=1 NUM_SLICE=1
//   0 = L1D    TLC port master_port_0_0     (channels A/B/C/D/E)
//   1 = Matrix TLM port master_m_port_0_0_0 (channels A/D + user_matrix)
//
// The DUT's memory side (mem_axi_0) goes to the tl-test AXI memory backend
// through the MemoryAXI DPI entries, in the same loop positions as v3_main
// under TLTEST_MEMORY=1.

`timescale 1ns/1ps

